export function translate(
  language: Language,
  key: TranslationKey,
  params?: Record<string, string | number>,
) {
  let value: string =
    key in attemptsConversionV2.en
      ? attemptsConversionV2[language][key as keyof typeof attemptsConversionV2.en]
      : copy[language][key as keyof typeof en];
  for (const [name, replacement] of Object.entries(params ?? {}))
    value = value.replace(`{${name}}`, String(replacement));
  return value;
}

