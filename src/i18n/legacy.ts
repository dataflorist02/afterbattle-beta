const metric = (language: Language, value: number | null) =>
  value === null
    ? "—"
    : new Intl.NumberFormat(language === "pl" ? "pl-PL" : "en-GB", {
        maximumFractionDigits: 0,
      }).format(value);
export function feedbackText(language: Language, item: FeedbackItem) {
  return (feedback[language][item.code] ?? item.code)
    .replace("{actual}", metric(language, item.actual))
    .replace("{baseline}", metric(language, item.baseline));
}
export function confidenceText(language: Language, confidence: Confidence) {
  return {
    en: { low: "low", medium: "medium", high: "high" },
    pl: { low: "niska", medium: "średnia", high: "wysoka" },
  }[language][confidence];
}
